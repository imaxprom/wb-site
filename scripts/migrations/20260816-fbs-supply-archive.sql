      EXECUTE format('GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA %I TO mphub_app', org.data_schema);
    END LOOP;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'mphub_readonly') THEN
    GRANT SELECT ON public.fbs_order_status_events TO mphub_readonly;
    GRANT SELECT ON public.fbs_sales_events TO mphub_readonly;
    GRANT SELECT ON public.fbs_archive_sync_state TO mphub_readonly;
    FOR org IN SELECT data_schema FROM public.organizations WHERE data_schema <> 'public' LOOP
      EXECUTE format('GRANT USAGE ON SCHEMA %I TO mphub_readonly', org.data_schema);
      EXECUTE format('GRANT SELECT ON %I.fbs_order_status_events TO mphub_readonly', org.data_schema);
      EXECUTE format('GRANT SELECT ON %I.fbs_sales_events TO mphub_readonly', org.data_schema);
      EXECUTE format('GRANT SELECT ON %I.fbs_archive_sync_state TO mphub_readonly', org.data_schema);
    END LOOP;
  END IF;
END
$archive_grants$;

COMMIT;
